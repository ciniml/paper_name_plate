//! 4-gray waveform tables for the PaperMono 3.97" panel.
//!
//! Layout (110 bytes): 105 waveform bytes for command 0x32
//! (5 VS groups x 10 bytes, 10 TP/RP groups x 5 bytes, 5 frame-rate bytes)
//! followed by `[VGH, VSH1, VSH2, VSL, VCOM]` for commands 0x03 / 0x04 / 0x2C.
//!
//! RAM group selection for the *absolute* waveforms (quality/text/fast):
//! group = RED bit << 1 | BW bit, with 0 = white, 1 = light gray,
//! 2 = dark gray, 3 = black.
//!
//! Tables are taken from M5GFX `Panel_SSD1677.cpp` (LovyanGFX, FreeBSD
//! licence, (c) lovyan03 and contributors).

pub const LUT_LEN: usize = 110;

